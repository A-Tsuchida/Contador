module Icons
open FluentIcons.Avalonia
open FluentIcons.Common

let playIcon =
  let icon = new FluentIcon()
  icon.Icon <- Icon.Play
  icon

let stopIcon =
  let icon = new FluentIcon()
  icon.Icon <- Icon.Stop
  icon

let lockIcon =
  let icon = new FluentIcon()
  icon.Icon <- Icon.LockClosed
  icon

let unlockIcon =
  let icon = new FluentIcon()
  icon.Icon <- Icon.LockClosed
  icon

